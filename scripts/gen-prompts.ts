// pnpm ai:prompts: compiles packages/core/src/ai/prompts/<task>/v<N>.md into generated.ts so prompts are
// bundled with the serverless functions (no runtime fs reads). The .md files stay the source of truth;
// a unit test fails if generated.ts is stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = path.resolve(import.meta.dirname, '../packages/core/src/ai/prompts');

export function renderPrompts(): string {
  const entries: string[] = [];
  for (const task of readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort()) {
    for (const file of readdirSync(path.join(dir, task))
      .filter((f) => /^v\d+\.md$/.test(f))
      .sort()) {
      const key = `${task}@${file.replace(/\.md$/, '')}`;
      entries.push(
        `  ${JSON.stringify(key)}: ${JSON.stringify(readFileSync(path.join(dir, task, file), 'utf8'))},`,
      );
    }
  }
  return `// GENERATED by \`pnpm ai:prompts\` from ./<task>/v<N>.md. Do not edit by hand.\nexport const RAW_PROMPTS: Record<string, string> = {\n${entries.join('\n')}\n};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  writeFileSync(path.join(dir, 'generated.ts'), renderPrompts());
  console.log('wrote prompts/generated.ts');
}
